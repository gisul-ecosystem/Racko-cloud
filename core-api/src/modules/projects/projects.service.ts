  async update(
    userId: string,
    projectId: string,
    input: UpdateProjectInput
  ): Promise<ProjectPublic> {
    const { orgId } = await assertOrgOwner(userId);
    const doc = await ProjectModel.findOne({
      _id: new mongoose.Types.ObjectId(projectId),
      orgId,
    });
    if (!doc) throw new NotFoundError('Project not found.');
    if (doc.status === 'archived') {
      throw new ValidationError('Archived projects cannot be edited.');
    }

    if (input.name !== undefined) doc.name = input.name.trim();
    if (input.clientName !== undefined) doc.clientName = input.clientName.trim();
    if (input.description !== undefined) {
      doc.description = input.description?.trim() || undefined;
    }
    await doc.save();
    const resourceCounts = await resourceCountsByService(doc);
    return toPublic(doc, resourceCounts);
  }

  async addServices(
    userId: string,
    projectId: string,
    input: AddProjectServicesInput
  ): Promise<ProjectPublic> {
    const { orgId } = await assertOrgOwner(userId);
    const doc = await ProjectModel.findOne({
      _id: new mongoose.Types.ObjectId(projectId),
      orgId,
    });
    if (!doc) throw new NotFoundError('Project not found.');
    if (doc.status === 'archived') {
      throw new ValidationError('Archived projects cannot be updated.');
    }

    const allowed = await getActiveOrgServiceKeys(orgId);
    const toAdd = assertServicesSubset(input.services, allowed);
    const merged = new Set([...doc.enabledServices, ...toAdd]);
    doc.enabledServices = [...merged] as AdminServiceKey[];
    await doc.save();
    const resourceCounts = await resourceCountsByService(doc);
    return toPublic(doc, resourceCounts);
  }

  async removeService(
    userId: string,
    projectId: string,
    serviceKey: string
  ): Promise<ProjectPublic> {
    const { orgId } = await assertOrgOwner(userId);
    if (!isAdminServiceKey(serviceKey)) {
      throw new ValidationError(`Unknown service "${serviceKey}".`);
    }

    const doc = await ProjectModel.findOne({
      _id: new mongoose.Types.ObjectId(projectId),
      orgId,
    });
    if (!doc) throw new NotFoundError('Project not found.');
    if (doc.status === 'archived') {
      throw new ValidationError('Archived projects cannot be updated.');
    }
    if (!doc.enabledServices.includes(serviceKey)) {
      throw new ValidationError(`Service "${serviceKey}" is not enabled on this project.`);
    }

    const count = await countResourcesForService(doc._id, serviceKey);
    if (count > 0) {
      throw new ValidationError(
        `Cannot remove "${serviceKey}" while ${count} resource(s) exist under this project.`
      );
    }

    doc.enabledServices = doc.enabledServices.filter((k) => k !== serviceKey);
    await doc.save();
    const resourceCounts = await resourceCountsByService(doc);
    return toPublic(doc, resourceCounts);
  }

