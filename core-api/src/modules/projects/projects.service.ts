  async removeServiceForTenant(
    tenantId: string,
    projectId: string,
    serviceKey: string
  ): Promise<ProjectPublic> {
    if (!isAdminServiceKey(serviceKey)) {
      throw new ValidationError(`Unknown service "${serviceKey}".`);
    }
    const doc = await ProjectModel.findOne({
      _id: new mongoose.Types.ObjectId(projectId),
      ownerType: 'tenant',
      tenantId,
    });
    if (!doc) throw new NotFoundError('Project not found.');
    if (doc.status === 'archived') {
      throw new ValidationError('Archived projects cannot be updated.');
    }
    if (!doc.enabledServices.includes(serviceKey)) {
      throw new ValidationError(`Service "${serviceKey}" is not enabled on this project.`);
    }
    const count = await countResourcesForService(doc._id, serviceKey);
    if (count > 0) {
      throw new ValidationError(
        `Cannot remove "${serviceKey}" while ${count} resource(s) exist under this project.`
      );
    }
    doc.enabledServices = doc.enabledServices.filter((k) => k !== serviceKey);
    await doc.save();
    return toPublic(doc, await resourceCountsByService(doc));
  }

  async archiveForTenant(tenantId: string, projectId: string): Promise<ProjectPublic> {
    const doc = await ProjectModel.findOne({
      _id: new mongoose.Types.ObjectId(projectId),
      ownerType: 'tenant',
      tenantId,
    });
    if (!doc) throw new NotFoundError('Project not found.');
    doc.status = 'archived';
    await doc.save();
    return toPublic(doc, await resourceCountsByService(doc));
  }

  async assertUsableForTenantService(params: {
    projectId: string;
    tenantId: string;
    serviceKey: AdminServiceKey;
  }): Promise<{ projectId: mongoose.Types.ObjectId; tenantId: string }> {
    if (!mongoose.Types.ObjectId.isValid(params.projectId)) {
      throw new ValidationError('Invalid projectId.');
    }
    const doc = await ProjectModel.findOne({
      _id: new mongoose.Types.ObjectId(params.projectId),
      ownerType: 'tenant',
      tenantId: params.tenantId,
    });
    if (!doc) throw new NotFoundError('Project not found.');
    if (doc.status !== 'active') {
      throw new ValidationError('Project is archived and cannot accept new resources.');
    }
    if (!doc.enabledServices.includes(params.serviceKey)) {
      throw new ValidationError(
        `Service "${params.serviceKey}" is not enabled on this project.`
      );
    }
    return { projectId: doc._id, tenantId: params.tenantId };
  }

