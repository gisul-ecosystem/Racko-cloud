function toPublic(doc: IProject, resourceCounts?: Record<string, number>): ProjectPublic {
  return {
    id: doc._id.toString(),
    ownerType: doc.ownerType || 'org',
    orgId: doc.orgId ?? null,
    tenantId: doc.tenantId ?? null,
    name: doc.name,
    autoGeneratedName: doc.autoGeneratedName,
    year: doc.year,
    sequenceNumber: doc.sequenceNumber,
    clientName: doc.clientName,
    description: doc.description ?? null,
    enabledServices: [...doc.enabledServices],
    status: doc.status,
    createdBy: doc.createdBy.toString(),
    createdAt: doc.createdAt.toISOString(),
    updatedAt: doc.updatedAt.toISOString(),
    ...(resourceCounts ? { resourceCounts } : {}),
  };
}

function slugifyOrgName(raw: string): string {
  const slug = raw
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40);
  return slug || 'org';
}

async function resolveOrgSlug(orgId: string): Promise<string> {
  const access = await OrganizationAccessRequestModel.findOne({
    userId: new mongoose.Types.ObjectId(orgId),
    status: 'approved',
  })
    .select('companyName')
    .lean();
  if (access?.companyName) return slugifyOrgName(access.companyName);

  const user = await User.findById(orgId).select('email').lean();
  if (user?.email) {
    const local = String(user.email).split('@')[0] || 'org';
    return slugifyOrgName(local);
  }
  return 'org';
}

function padSequence(n: number): string {
  return String(n).padStart(3, '0');
}

async function resolveTenantSlug(tenantId: string): Promise<string> {
  const tenant = await Tenant.findById(tenantId).select('name slug').lean();
  if (tenant?.slug) return slugifyOrgName(tenant.slug);
  if (tenant?.name) return slugifyOrgName(tenant.name);
  return 'tenant';
}

async function assertTenantExists(tenantId: string): Promise<void> {
  if (!mongoose.Types.ObjectId.isValid(tenantId)) {
    throw new ValidationError('Invalid tenant id.');
  }
  const tenant = await Tenant.findById(tenantId).select('_id').lean();
  if (!tenant) throw new NotFoundError('Tenant not found.');
}

async function nextSequenceForOwner(params: {
  ownerType: ProjectOwnerType;
  orgId?: string;
  tenantId?: string;
  year: number;
}): Promise<number> {
  const filter =
    params.ownerType === 'tenant'
      ? { ownerType: 'tenant' as const, tenantId: params.tenantId, year: params.year }
      : { ownerType: 'org' as const, orgId: params.orgId, year: params.year };
  const latest = await ProjectModel.findOne(filter)
    .sort({ sequenceNumber: -1 })
    .select('sequenceNumber')
    .lean();
  return (latest?.sequenceNumber ?? 0) + 1;
}

async function nextSequence(orgId: string, year: number): Promise<number> {
  return nextSequenceForOwner({ ownerType: 'org', orgId, year });
}

async function assertOrgOwner(userId: string): Promise<{ orgId: string }> {
  const user = await User.findById(userId).select('role orgOwnerId isActive').lean();
  if (!user || !user.isActive || user.role !== 'admin') {
    throw new ForbiddenError('Only organization admins can manage projects.');
  }
  if (user.orgOwnerId) {
    throw new ForbiddenError('Only the organization owner can manage projects.');
  }
  const orgId = resolvePlatformOrgOwnerId({
    _id: user._id,
    role: user.role,
    orgOwnerId: user.orgOwnerId,
  });
  if (!orgId) throw new ForbiddenError('Organization context required.');
  return { orgId };
}

/** Resolve org owner id for super-admin acting on a customer admin. */
async function resolveTargetOrgOwnerId(adminId: string): Promise<string> {
  if (!mongoose.Types.ObjectId.isValid(adminId)) {
    throw new ValidationError('Invalid admin id.');
  }
  const user = await User.findById(adminId).select('role orgOwnerId isActive').lean();
  if (!user || !user.isActive || user.role !== 'admin') {
    throw new NotFoundError('Organization admin not found.');
  }
  if (user.orgOwnerId) {
    throw new ValidationError(
      'Projects belong to the organization owner. Open the owner account, not an operator.'
    );
  }
  const orgId = resolvePlatformOrgOwnerId({
    _id: user._id,
    role: user.role,
    orgOwnerId: user.orgOwnerId,
  });
  if (!orgId) throw new ValidationError('Organization context required.');
  return orgId;
}

async function createForOrg(
  orgId: string,
  createdByUserId: string,
  input: CreateProjectInput
): Promise<ProjectPublic> {
  const allowed = await getActiveOrgServiceKeys(orgId);
  const enabledServices = assertServicesSubset(input.enabledServices, allowed);

  const year = new Date().getUTCFullYear();
  const sequenceNumber = await nextSequenceForOwner({ ownerType: 'org', orgId, year });
  const slug = await resolveOrgSlug(orgId);
  const autoGeneratedName = `${slug}-${year}-project-${padSequence(sequenceNumber)}`;
  const name = (input.name?.trim() || autoGeneratedName).slice(0, 200);

  const doc = await ProjectModel.create({
    ownerType: 'org',
    orgId,
    name,
    autoGeneratedName,
    year,
    sequenceNumber,
    clientName: input.clientName.trim(),
    description: input.description?.trim() || undefined,
    enabledServices,
    status: 'active',
    createdBy: new mongoose.Types.ObjectId(createdByUserId),
  });

  return toPublic(doc, Object.fromEntries(enabledServices.map((k) => [k, 0])));
}

